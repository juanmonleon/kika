"""Compton profiles for the photo-atomic tables: Biggs-Mendelsohn-Mann, matched to the evaluation's subshells.

ENDF carries no Compton profiles; every photo-atomic library adds them from
Biggs, Mendelsohn and Mann (1975), as OpenMC and NJOY3 do. The table is
packaged in ``data/bmm_compton_profiles.npz`` (regenerated by
``data/make_bmm_table.py``): per element, the shells BMM tabulates, labelled
``"1s"``, ``"2p"`` (Z < 36, non-relativistic) or ``"2p3/2"`` (Z ≥ 36), and J(p_z)
on 31 momenta.

**Matching shells to subshells** (:func:`comptonShells`). A Compton shell is a
BMM shell with the electron number and binding energy of the evaluation's
subshells it stands for:

- a BMM shell without j (Z < 36) stands for every subshell of the same n and l
  (2p for 2p1/2 and 2p3/2);
- a BMM shell with j stands for the subshell of the same n, l and j and for any
  subshell of the same n and l whose j BMM does not list (BMM gives Pb only
  6p1/2; the evaluation's 6p3/2 joins it);
- a BMM shell with no subshell in the evaluation is dropped (Ir 6s1/2).

Its electron number is the sum over those subshells, its binding energy their
population-weighted mean, so the arrays the table writes (LNEPS, LBEPS, LPIPS)
have one entry per profile. eprdata25 writes one entry per evaluated subshell
with one profile per BMM shell, which in 25 elements leaves the three arrays
one or two places out of step with the profiles and with each other.
"""
from __future__ import annotations

import re
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import List, Optional, Tuple

import numpy as np

__all__ = ["ComptonShell", "bmmProfiles", "comptonShells"]

_DATA = Path(__file__).with_name("data") / "bmm_compton_profiles.npz"
_LABEL = re.compile(r"(\d+)([spdfgh])(?:(\d+)/2)?$")


@dataclass
class ComptonShell:
    """One Compton shell of a table: its profile and the subshells it stands for."""

    label: str
    electrons: float
    bindingEnergy: float          # eV
    pz: np.ndarray                # atomic units
    pdf: np.ndarray
    cdf: np.ndarray
    subshells: Tuple[str, ...]


@lru_cache(maxsize=1)
def _table():
    with np.load(_DATA) as data:
        return {key: data[key] for key in data.files}


def bmmProfiles(z: int) -> Tuple[np.ndarray, List[str], np.ndarray]:
    """``(p_z, labels, J)`` of element ``z``: J unnormalised, one row per BMM shell."""
    t = _table()
    if f"labels_{z}" not in t:
        raise KeyError(f"Biggs-Mendelsohn-Mann tabulate no profiles for Z = {z}")
    return t["pz"], [str(v) for v in t[f"labels_{z}"]], t[f"J_{z}"]


def _parse(label: str) -> Tuple[int, str, Optional[int]]:
    m = _LABEL.match(label)
    if m is None:
        raise ValueError(f"{label!r} is not a shell label")
    return int(m.group(1)), m.group(2), int(m.group(3)) if m.group(3) else None


def _normalised(pz: np.ndarray, j: np.ndarray):
    """``pdf = J / ∫J`` and its cumulative trapezoid, the last value set to 1."""
    pieces = 0.5 * np.diff(pz) * (j[:-1] + j[1:])
    area = 0.0
    for p in pieces:                     # summed left to right, as the reference does
        area += p
    pdf = j / area
    steps = 0.5 * np.diff(pz) * (pdf[:-1] + pdf[1:])
    cdf = np.concatenate(([0.0], np.cumsum(steps)))
    cdf[-1] = 1.0
    return pdf, cdf


def comptonShells(z: int, subshells) -> Tuple[List[ComptonShell], List[str]]:
    """``(shells, notes)``: BMM's shells of ``z`` matched to the evaluation's ``subshells``.

    ``subshells`` is ``[(label, electrons, binding energy in eV), ...]`` in the
    evaluation's order. ``notes`` names every BMM shell dropped and every
    subshell joined to a sibling or left without a profile.
    """
    pz, labels, js = bmmProfiles(z)
    parsed = [(label, *_parse(label)) for label in labels]
    listed = {(n, l, j) for _, n, l, j in parsed}
    notes, used, shells = [], set(), []
    for (label, n, l, j), profile in zip(parsed, js):
        members = []
        for name, electrons, binding in subshells:
            sn, sl, sj = _parse(name)
            if (sn, sl) != (n, l):
                continue
            if j is None or sj == j or (sn, sl, sj) not in listed:
                members.append((name, electrons, binding))
        if not members:
            notes.append(f"BMM shell {label} has no subshell in the evaluation; its profile is not written")
            continue
        for name, _, _ in members:
            if name in used:
                raise ValueError(f"subshell {name} would stand in two Compton shells")
            used.add(name)
            if j is not None and _parse(name)[2] != j:
                notes.append(f"subshell {name} has no BMM profile; it joins {label}")
        electrons = sum(e for _, e, _ in members)
        binding = sum(e * b for _, e, b in members) / electrons
        pdf, cdf = _normalised(np.asarray(pz, dtype=float), np.asarray(profile, dtype=float))
        shells.append(ComptonShell(label, float(electrons), float(binding), np.asarray(pz, dtype=float),
                                   pdf, cdf, tuple(name for name, _, _ in members)))
    for name, _, _ in subshells:
        if name not in used:
            notes.append(f"subshell {name} has no BMM shell of its n and l; no Compton profile")
    return shells, notes
