import pytest

from kika.materials import MaterialCollection, read_material
from kika.materials._zaid import identity
from kika.mcnp.parse_input import read_mcnp


def test_every_keyword_is_kept_and_written_back():
    material, _ = read_material(["m3 1001.80c 2 8016.80c 1 hlib=70h pnlib = 70u gas=1 cond=-1"], 0)
    assert material.libs == {"hlib": "70h", "pnlib": "70u"}
    assert material.keywords == {"gas": "1", "cond": "-1"}
    assert not material.report.warnings
    again, _ = read_material(material.to_mcnp().splitlines(), 0)
    assert again.libs == material.libs and again.keywords == material.keywords


def test_an_unknown_keyword_is_kept_and_reported():
    material, _ = read_material(["m1 1001.80c 1 frob=2"], 0)
    assert material.keywords == {"frob": "2"}
    assert any("frob" in w for w in material.report.warnings)


def test_continuations_comments_and_the_blank_line_that_ends_the_card():
    lines = [
        "m4 1001.80c 2 $ hydrogen &",
        "c a comment inside the card",
        "     8016.80c 1",
        "     nlib=80c",
        "\t6000.80c 0.5",
        "",
        "     26056.80c 1",
    ]
    material, end = read_material(lines, 0)
    assert sorted(material.nuclide.keys()) == ["C", "H1", "O16"]
    assert material.libs == {"nlib": "80c"}
    assert end == 5


def test_a_token_that_is_not_a_keyword_or_a_nuclide_is_refused():
    with pytest.raises(ValueError, match="neither a keyword"):
        read_material(["m1 1001.80c 1 8016.80c"], 0)


@pytest.mark.parametrize("zaid, expected", [
    (95642, (95, 242, 1)), (95342, (95, 242, 1)), (1095242, (95, 242, 1)),
    (27458, (27, 58, 1)), (27358, (27, 58, 1)), (47306, (47, 106, 1)),
    (26056, (26, 56, 0)), (6000, (6, 0, 0)),
])
def test_isomer_zaids_in_every_convention_name_the_same_nuclide(zaid, expected):
    assert identity(zaid) == expected


def test_an_isomer_keeps_its_zaid_and_gets_its_name():
    material, _ = read_material(["m1 95642.80c 1 95241.80c 1"], 0)
    assert sorted(material.nuclide.keys()) == ["Am241", "Am242m"]
    assert "95642.80c" in material.to_mcnp()
    material.to_weight_fraction()
    assert material.nuclide["Am242m"].fraction == pytest.approx(242.0596 / (242.0596 + 241.0568), rel=1e-5)


def test_an_isomer_given_by_symbol_is_written_in_the_lanl_form():
    from kika.materials import Material
    material = Material(id=1)
    material.add_nuclide("Am242m", 1.0, "ao", library="80c")
    assert "95642.80c" in material.to_mcnp()


DECK = (
    "title\n1 1 -1.0 -1 imp:n=1\n2 0 1 imp:n=0\n\n1 so 10\n\n"
    "m1 1001.80c 2 8016.80c 1\nmt1 lwtr.20t\nf4:n 1\nnps 100\n"
)


def test_the_mt_card_belongs_to_its_material(tmp_path):
    path = tmp_path / "deck.i"
    path.write_text(DECK)
    deck = read_mcnp(str(path))
    assert deck.materials.by_id[1].thermal_scattering == ["lwtr.20t"]
    assert "mt1 lwtr.20t" in deck.materials.by_id[1].to_mcnp()


def test_rewriting_a_material_with_its_mt_card_keeps_one_mt_card(tmp_path):
    path = tmp_path / "deck.i"
    path.write_text(DECK)
    collection = read_mcnp(str(path)).materials
    collection.by_id[1].update_nuclide_fraction("O16", 1.1)
    collection.by_id[1].thermal_scattering = ["lwtr.21t"]
    assert collection.write_to_mcnp(str(path)) == [1]
    collection.by_id[1].update_nuclide_fraction("O16", 1.2)
    assert collection.write_to_mcnp(str(path)) == [1]
    text = path.read_text()
    assert text.count("mt1") == 1 and "lwtr.21t" in text
    assert text.count("Generated by KIKA") == 1
    assert "f4:n 1" in text


def test_a_material_without_tables_leaves_the_mt_card_alone(tmp_path):
    path = tmp_path / "deck.i"
    path.write_text(DECK)
    collection = MaterialCollection()
    material, _ = read_material(["m1 1001.80c 2 8016.80c 1.1"], 0)
    collection.add_material(material)
    collection.write_to_mcnp(str(path))
    collection.by_id[1].update_nuclide_fraction("O16", 1.2)
    collection.write_to_mcnp(str(path))
    assert path.read_text().count("mt1 lwtr.20t") == 1
