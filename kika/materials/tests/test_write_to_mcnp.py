from kika.materials import MaterialCollection, read_material

DECK = (
    "title\n"
    "1 1 -1.0 -1 imp:n=1\n"
    "2 0 1 imp:n=0\n"
    "\n"
    "1 so 10\n"
    "\n"
    "mode n\n"
    "m1 1001.80c 2 8016.80c 1 nlib=80c\n"
    "mt1 lwtr.20t\n"
    "f4:n 1\n"
    "M2 26056.80c 1\n"
    "     26054.80c 0.06\n"
    "nps 100\n"
)


def collection_of(*cards):
    collection = MaterialCollection()
    for card in cards:
        material, _ = read_material(card.splitlines(), 0)
        collection.add_material(material)
    return collection


def write(tmp_path, text, newline="\n"):
    path = tmp_path / "deck.i"
    path.write_bytes(text.replace("\n", newline).encode())
    return path


def test_force_rewrite_keeps_the_cards_between_materials(tmp_path):
    path = write(tmp_path, DECK)
    collection = collection_of("m1 1001.80c 2 8016.80c 1 nlib=80c", "m2 26056.80c 1 26054.80c 0.06")
    assert collection.write_to_mcnp(str(path), force_rewrite=True) == [1, 2]
    text = path.read_text()
    for card in ("mt1 lwtr.20t", "f4:n 1", "mode n", "nps 100"):
        assert card in text


def test_a_change_of_material_library_alone_is_written(tmp_path):
    path = write(tmp_path, DECK)
    collection = collection_of("m1 1001.80c 2 8016.80c 1 nlib=70c")
    assert collection.write_to_mcnp(str(path)) == [1]
    assert "nlib=70c" in path.read_text()


def test_an_uppercase_material_card_is_updated_in_place(tmp_path):
    path = write(tmp_path, DECK)
    collection = collection_of("m2 26056.80c 1 26054.80c 0.07")
    assert collection.write_to_mcnp(str(path)) == [2]
    text = path.read_text()
    assert "M2 26056.80c 1" not in text
    assert text.count("m2") == 1


def test_writing_twice_replaces_the_same_block(tmp_path):
    path = write(tmp_path, DECK)
    collection = collection_of("m1 1001.80c 2 8016.80c 1.1 nlib=80c")
    collection.by_id[1].name = "water"
    collection.write_to_mcnp(str(path))
    first = path.read_text()
    collection.by_id[1].update_nuclide_fraction("O16", 1.2)
    collection.write_to_mcnp(str(path))
    second = path.read_text()
    assert second.count("KIKA_MAT_NAME") == 1
    assert second.count("Generated by KIKA") == first.count("Generated by KIKA") == 1
    assert len(second.splitlines()) == len(first.splitlines())


def test_unchanged_lines_and_line_endings_are_kept_byte_for_byte(tmp_path):
    path = write(tmp_path, DECK + "c caf\xe9\n", newline="\r\n")
    path.write_bytes(path.read_bytes().replace("é".encode(), b"\xe9"))
    before = path.read_bytes()
    collection = collection_of("m2 26056.80c 1 26054.80c 0.07")
    collection.write_to_mcnp(str(path))
    after = path.read_bytes()
    assert b"\r\n" in after and after.count(b"\n") == after.count(b"\r\n")
    assert b"c caf\xe9\r\n" in after
    assert after.startswith(before.split(b"M2 ")[0])


def test_a_new_material_goes_after_the_last_one(tmp_path):
    path = write(tmp_path, DECK)
    collection = collection_of("m1 1001.80c 2 8016.80c 1 nlib=70c", "m5 6000.80c 1")
    assert collection.write_to_mcnp(str(path)) == [1, 5]
    lines = path.read_text().splitlines()
    assert lines.index("m5") > lines.index("     26054.80c 0.06")
    assert lines.index("m5") < lines.index("nps 100")
